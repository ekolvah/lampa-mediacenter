(function () {
  // Шаг 3 (после рестарта): отсканированный на шаге 2 KP-тайтл сохранён на диске с отметкой скана.
  // Потерянную запись проход плагина вставил бы заново, но без scan. SCANNED '-' — все KP-тайтлы
  // были отсканированы ещё до проверки, то есть их отметки уже пережили прошлые рестарты.
  if (SCANNED === '-') return 'ok: все KP-тайтлы отсканированы до проверки';
  var disk = JSON.parse(localStorage.getItem('recomends_scan') || '[]');
  var entry = queued(disk, SCANNED);
  Live.check(entry && entry.scan, 'после рестарта у ' + SCANNED + ' нет отметки скана: запись потерялась');
  return 'ok: ' + SCANNED + ' отсканирован и сохранён';
})()
